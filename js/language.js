// CAMBIAR IDIOMA
function changeLanguage(language) {

    localStorage.setItem("language", language);

    document.querySelectorAll("[data-key]").forEach(element => {

        const key = element.getAttribute("data-key");

        if (translations[language][key]) {

            element.textContent = translations[language][key];
        }
    });

    // BOTONES ACTIVOS
    document.querySelectorAll(".lang-btn").forEach(btn => {

        btn.classList.remove("active");

        if (btn.textContent.trim().toLowerCase() === language) {

            btn.classList.add("active");
        }
    });

    // CAMBIAR ATRIBUTOS PLACEHOLDER
    const placeholders = {

        es: {
            nombre: "Ingresa tu nombre",
            correo: "ejemplo@email.com",
            asunto: "Escribe el asunto",
            mensaje: "Escribe tu mensaje"
        },

        en: {
            nombre: "Enter your name",
            correo: "example@email.com",
            asunto: "Write the subject",
            mensaje: "Write your message"
        }
    };

    const nombre = document.getElementById("nombre");
    const correo = document.getElementById("correo");
    const asunto = document.getElementById("asunto");
    const mensaje = document.getElementById("mensaje-contacto");

    if (nombre) nombre.placeholder = placeholders[language].nombre;
    if (correo) correo.placeholder = placeholders[language].correo;
    if (asunto) asunto.placeholder = placeholders[language].asunto;
    if (mensaje) mensaje.placeholder = placeholders[language].mensaje;
}

// CARGAR IDIOMA GUARDADO
document.addEventListener("DOMContentLoaded", () => {

    const savedLanguage = localStorage.getItem("language") || "es";

    changeLanguage(savedLanguage);
});